const FormData = require("form-data");
const userApi = require("../config/axios");

module.exports.forwardSendMail = async (request, reply) => {
    try {
        console.log("Forward controller reached");

        const fields = request.sendMailFields;
        const document = request.sendMailDocument;

        if (!fields || !document) {
            return reply.code(400).send({
                success: false,
                message: "Validated template fields or document are missing"
            });
        }

        // Rebuild multipart data for user-service.
        const form = new FormData();

        form.append("templateId", fields.templateId);

        form.append("document", document.buffer, {
            filename: document.filename,
            contentType: document.mimetype
        });

        // Use the new multipart boundary generated by FormData.
        const headers = {
            ...form.getHeaders()
        };

        // Forward authentication headers.
        for (const name of [
            "authorization",
            "x-api-key",
            "accept"
        ]) {
            if (request.headers[name]) {
                headers[name] = request.headers[name];
            }
        }

        console.log("Forwarding CSV to user-service");

        const response = await userApi.request({
            method: request.method,
            url: request.raw.url,
            data: form,
            headers,
            maxBodyLength: Infinity,
            maxContentLength: Infinity
        });

        console.log("User-service response:", response.status);

        return reply
            .code(response.status)
            .send(response.data);

    } catch (error) {
        request.log.error(
            {
                message: error.message,
                downstreamStatus: error.response?.status,
                downstreamData: error.response?.data
            },
            "Send-mail forwarding failed"
        );

        if (error.response) {
            return reply
                .code(error.response.status)
                .send(error.response.data);
        }

        return reply.code(502).send({
            success: false,
            message: "UserService is unavailable"
        });
    }
};
